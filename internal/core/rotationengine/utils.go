package rotationengine

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"
)

const logFilePattern = "autogenerated-%s.log"

type logFile struct {
	name string
	date time.Time
	part int
	size uint
}

// getFileDate gets the date from the log file name.
// It returns the date and an error if the date couldn't be parsed.
// The date is parsed in the local timezone, matching how createNewFile
// names files from time.Now(), so callers can safely compare the result
// against other local times (e.g. time.Now()).
func (r *rotationEngine) getFileDate(file string) (time.Time, error) {
	dateStr, _, _ := strings.Cut(strings.TrimPrefix(file, "autogenerated-"), ".")
	return time.ParseInLocation(time.DateOnly, dateStr, time.Local)
}

// getAllfiles gets all the files in the folder.
// It returns the log files, oldest first, and an error if it couldn't read the folder.
func (r *rotationEngine) getAllfiles() ([]logFile, error) {
	files, err := r.ReadDir(r.folder)
	if err != nil {
		return nil, err
	}

	filePattern := regexp.MustCompile(`^autogenerated-(\d{4}-\d{2}-\d{2})(?:\.(\d+))?\.log$`)

	var filenames = make([]logFile, 0, len(files))
	for _, file := range files {
		if file.IsDir() {
			continue
		}

		m := filePattern.FindStringSubmatch(file.Name())
		if m == nil {
			fmt.Fprintf(os.Stderr, "[ionlog internal log] file: %s is not a valid log file. Skipping.\n", file.Name())
			continue
		}

		fileTime, err := r.getFileDate(file.Name())
		if err != nil {
			fmt.Fprintf(os.Stderr, "[ionlog internal log] Failed to get file date for file: %s. Skipping.\n", file.Name())
			continue
		}

		info, err := file.Info()
		if err != nil {
			return nil, err
		}

		part, _ := strconv.Atoi(m[2])
		filenames = append(filenames, logFile{name: file.Name(), date: fileTime, part: part, size: uint(info.Size())})
	}

	sort.Slice(filenames, func(i, j int) bool {
		a, b := filenames[i], filenames[j]
		return a.date.Before(b.date) || a.date.Equal(b.date) && a.part < b.part
	})
	return filenames, nil
}

// createNewFile creates a new log file in the specified folder.
func (r *rotationEngine) createNewFile(date time.Time, part int) error {
	y, m, d := date.Date()
	date = time.Date(y, m, d, 0, 0, 0, 0, time.Local)
	_, err := r.ReadDir(r.folder)
	if err != nil {
		return err
	}

	filename := fmt.Sprintf(logFilePattern, date.Format(time.DateOnly))
	if part > 0 {
		filename = fmt.Sprintf("autogenerated-%s.%d.log", date.Format(time.DateOnly), part)
	}
	filePath := filepath.Join(r.folder, filename)

	f, err := r.OpenFile(filePath, os.O_WRONLY|os.O_CREATE|os.O_APPEND, 0644)
	if err != nil {
		return err
	}

	r.setLogFile(f)
	r.files = append(r.files, logFile{name: filename, date: date, part: part})
	return nil
}

// assertFolder checks if the folder exists and creates it if it does not,
// it returns an error if the folder could not be created, or if it could not be checked.
func (r *rotationEngine) assertFolder() error {
	_, err := r.Stat(r.folder)
	if err == nil {
		return nil
	}

	if errors.Is(err, os.ErrNotExist) {
		if err := r.Mkdir(r.folder, 0755); err != nil {
			return err
		}
		return nil
	}

	return err // some other error
}

// checkRotation checks if the log file needs to be rotated based on the rotation type.
// It returns true if the log file needs to be rotated and false if it doesn't.
func (r *rotationEngine) checkRotation(fileDate time.Time) bool {
	now := r.now()
	y, m, d := now.Date()

	switch r.rotation {
	case Daily:
		return fileDate.Year() != y || fileDate.Month() != m || fileDate.Day() != d
	case Weekly:
		isoYear, w := now.ISOWeek()
		fileISOYear, fileW := fileDate.ISOWeek()
		return fileISOYear != isoYear || fileW != w
	case Monthly:
		return fileDate.Year() != y || fileDate.Month() != m
	default:
		return false
	}
}
